
from dataclasses import dataclass, fields, field
from pathlib import Path
import logging
from functools import wraps
import time
import traceback

_logger = logging.getLogger(__name__)

log_levels = {
    "stats": logging.DEBUG,
    "debug": logging.DEBUG,
    "info": logging.INFO,
    "warning": logging.WARNING,
    "error": logging.ERROR,
    "critical": logging.CRITICAL,
}

def report_perf(cls):
    for name, attr in cls.__dict__.items():
        if name.startswith(("__", "log", "error",)):
            continue

        if isinstance(attr, property):
            pass
        elif isinstance(attr, staticmethod):
            pass
        elif callable(attr):
            @wraps(attr)
            def wrapper(self, *args, __fn=attr, __name=name, **kwargs):
                t0 = time.perf_counter()
                error = False
                try:
                    return __fn(self, *args, **kwargs)
                except Exception as e:
                    self.error(__name, e)
                    error = True
                    raise
                finally:
                    if not error:
                        self.log("info", f"[{__name}] resolved within: ({time.perf_counter() - t0:.4f}s)")
            setattr(cls, name, wrapper)
    return cls

@dataclass
@report_perf
class KaraokeTask:
    id: int

    source: str

    title: str | None = None
    artist: str | None = None
    duration: float | None = None
    thumbnail: str | None = None

    _video_path: Path | None = None
    _audio_path: Path | None = None
    _vocal_path: Path | None = None
    _instrument_path : Path | None = None

    _error_entries: list[tuple] = field(default_factory=list)
    _log_entries: list[tuple] = field(default_factory=list)
    logger: logging.Logger | None = None

    def __post_init__(self):
        if not self.logger:
            self.logger = logging.getLogger(f"iantirta.karaoke.Task({self.id!s})")
    
    def log(self, loglevel, message, *args, **kwargs) -> None:
        self._log_entries.append((loglevel, message, args, kwargs))
        if loglevel in log_levels:
            self.logger.log(log_levels[loglevel], message, *args, **kwargs)

    def error(self, fn_name: str, error: Exception) -> None:
        err_msg = str(error)
        tb_str = traceback.format_exc()
        
        self._error_entries.append((fn_name, type(error), err_msg, tb_str))
        self.log("error", f"[{fn_name}] {err_msg}")

    @classmethod
    def from_dict(cls, **datas) -> "KaraokeTask":
        valid_keys = {f.name for f in fields(cls)}
        valid_datas = {k: v for k, v in datas.items() if k in valid_keys}
        
        return cls(**valid_datas)

    @property
    def video_path(self) -> Path:
        if self._video_path is None:
            if self.source.startswith(("http://", "https://")):
                self._download_video()

            elif Path(self.source).is_file():
                self._video_path = Path(self.source)

            else:
                raise ValueError(f"Unknown source origin: {self.source}")

        return self._video_path

    @video_path.setter
    def video_path(self, value: str | Path):
        # Little bit of validation
        if not Path(value).is_file():
            raise FileNotFoundError(f"File Not Exist: {value}")

        else:
            self._video_path = Path(value)

    def _download_video(self):
        from iantirta.media import VideoDownloader, VideoMetadata
        try:
            metadata: VideoMetadata = VideoDownloader().download(self.source)
        except Exception as e:
            raise

        self.video_path = metadata.video_path

        if self.duration and self.duration != metadata.duration:
            self.logger.warning(f"Different duration generated by new download, overwriting...")
        self.duration = metadata.duration

        if self.title and self.title != metadata.title:
            self.logger.warning(f"Different title generated by new download, overwriting...")
        self.title = metadata.title

        if self.artist and self.artist != metadata.resolved_artist:
            self.logger.warning(f"Different artist generated by new download, overwriting...")
        self.artist = metadata.resolved_artist

        if self.thumbnail and self.thumbnail != metadata.thumbnail:
            self.logger.warning(f"Metadata thumbnail is different, you can ignore this warning.")
        self.thumbnail = metadata.thumbnail

        del metadata

    @property
    def audio_path(self) -> Path:
        if self._audio_path is None or not self._audio_path.is_file():
            self._audio_path = self.video_path.with_suffix(".wav")

            if not self._audio_path.is_file():
                import subprocess
                try:
                    subprocess.run([
                        "ffmpeg", "-y",
                        "-i", str(self._video_path),
                        "-vn", str(self._audio_path)
                    ], check=True, capture_output=True, text=True,)
                except Exception:
                    raise

                if not self._audio_path.is_file():
                    raise

        return self._audio_path

    @audio_path.setter
    def audio_path(self, value: str | Path):
        if not Path(value).is_file():
            raise FileNotFoundError(f"Audio File Not Exist: {value}")

        else:
            self._audio_path = Path(value)

    def get_audio_path(self) -> Path:
        return self.audio_path

    @property
    def vocal_path(self):
        if self._vocal_path is None or not self._vocal_path.is_file():
            self._vocal_path = self.audio_path.with_name(self.audio_path.stem + "_vocal.wav")

            if not self._vocal_path.is_file():
                try:
                    self._separate_vocal_and_instrument()

                except Exception as e:
                    raise

                else:
                    if not self._vocal_path.is_file():
                        raise OSError("Separating return success but vocal path doesnt exists.")

        return self._vocal_path

    @vocal_path.setter
    def vocal_path(self, value: str | Path):
        if not Path(value).is_file():
            raise FileNotFoundError(f"Vocal File Not Exist: {value}")

        else:
            self._vocal_path = Path(value)

    def _separate_vocal_and_instrument(self, separator=None):
        if separator is None:
            from iantirta.models.load_model import load_model
            separator = load_model("adefossez/Demucs-mdx_extra_q", "separation")

        try:
            result: SeparationData = separator.separate(self.audio_path, )
        except Exception:
            raise

        from iantirta.audio import save_audio
        save_audio(result.vocal, self._vocal_path)
        save_audio(result.instrument, self._instrument_path)

    @property
    def lyrics(self):
        if self._lyrics is None:
            pass

        return self._lyrics

    @lyrics.setter
    def lyrics(self, value: str):
        self._lyrics = value


